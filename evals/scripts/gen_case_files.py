"""Generate module-level smelt case files for every skill with references.

Reads the REF_CASES table from tests/test_evaluate_all.py (single source of
truth for bilingual triggers) and emits one case file per (lang, skill) into
cases/ — each with one reference_read case per reference file, ready for:

    uv run smelt run cases/zh-cn_api-design_cases.py -v
    uv run smelt doctor --skill ../skills/zh-cn/api-design cases/zh-cn_api-design_cases.py

Usage: uv run python scripts/gen_case_files.py
"""

from __future__ import annotations

import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(EVALS / "tests"))
sys.path.insert(0, str(EVALS))  # conftest.py

from test_evaluate_all import REF_CASES  # noqa: E402

TEMPLATE = '''"""Auto-generated by scripts/gen_case_files.py — do not edit by hand."""

from __future__ import annotations

import os
from pathlib import Path

import smelt
from smelt import (
    OpenAIChatClient,
    context,
    llm_judge,
    new_case,
    reference_folder,
    reference_read,
    smelt_agent,
    text,
    tool,
)

smelt.load_env(Path(__file__).resolve().parent.parent / ".env")

SKILL_DIR = Path(__file__).resolve().parent.parent.parent / "skills" / "{lang}" / "{skill}"

REFERENCES_HINT = (
    "The skill's files are materialized in the current workspace. When the "
    "skill document points to reference files (e.g. references/xxx.md), read "
    "them with the read_file tool BEFORE answering, and follow them exactly."
)

JUDGE_CRITERIA = (
    "Score by whether the answer visibly builds on the referenced document's "
    "core convention (its pattern choice, structure, naming, tooling). "
    "Reasonable elaborations that keep the core convention score HIGH; "
    "answers that ignore the reference's approach and fall back to a generic "
    "or unrelated convention score LOW."
)


def _llm() -> OpenAIChatClient:
    kwargs: dict = {{}}
    if "deepseek" in os.environ.get("SMELT_BASE_URL", ""):
        kwargs["extra_body"] = {{"thinking": {{"type": "disabled"}}}}
    return OpenAIChatClient(
        model=os.environ.get("SMELT_AGENT_MODEL", "deepseek-v4-flash"),
        base_url=os.environ.get("SMELT_BASE_URL", "https://api.deepseek.com"),
        api_key=os.environ["SMELT_API_KEY"],
        **kwargs,
    )


@tool
def read_file(path: str) -> str:
    """Read a UTF-8 text file from the workspace and return its content."""
    p = Path(path)
    if not p.is_file():
        return f"file not found: {{path}}"
    return p.read_text(encoding="utf-8", errors="replace")[:8000]


{cases}

cases = [{case_names}]
'''

CASE_TEMPLATE = '''{var} = (
    new_case("ref-{stem}")
    .given(reference_folder(SKILL_DIR))
    .given(context(prompt=REFERENCES_HINT))
    .given(smelt_agent(SKILL_DIR, llm=_llm(), tools=[read_file]))
    .when(text({trigger!r}))
    .then(reference_read({ref!r}))
    .then(llm_judge(_llm(), criteria=JUDGE_CRITERIA, reference={excerpt!r},
                    threshold=0.6))
)'''


from conftest import extract_anchor_excerpt as _excerpt  # shared anchor extraction


def ref_for(ref_spec, lang):
    return ref_spec.get(lang) if isinstance(ref_spec, dict) else ref_spec


def main() -> None:
    out_dir = EVALS / "cases"
    out_dir.mkdir(exist_ok=True)
    written = 0
    for skill, entries in sorted(REF_CASES.items()):
        for lang in ("en", "zh-cn"):
            blocks, names = [], []
            for ref_spec, triggers in entries:
                ref, trigger = ref_for(ref_spec, lang), triggers.get(lang)
                if ref is None or trigger is None:
                    continue
                ref_file = EVALS.parent / "skills" / lang / skill / ref
                excerpt = _excerpt(ref_file, trigger) if ref_file.exists() else ""
                stem = Path(ref).stem.replace("-", "_")
                var = f"case_{stem}"
                names.append(var)
                blocks.append(CASE_TEMPLATE.format(
                    var=var, stem=Path(ref).stem, trigger=trigger, ref=ref,
                    excerpt=excerpt))
            if not blocks:
                continue
            (out_dir / f"{lang}_{skill}_cases.py").write_text(
                TEMPLATE.format(lang=lang, skill=skill,
                                cases="\n\n\n".join(blocks),
                                case_names=", ".join(names)))
            written += 1
    print(f"generated {written} case files under cases/")


if __name__ == "__main__":
    main()
